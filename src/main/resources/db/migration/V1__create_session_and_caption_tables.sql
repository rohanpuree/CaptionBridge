CREATE TABLE sessions (
    id UUID PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('LIVE', 'ENDED')),
    host_token_hash CHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    last_caption_seq BIGINT NOT NULL DEFAULT 0 CHECK (last_caption_seq >= 0)
);

CREATE TABLE caption_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    seq BIGINT NOT NULL CHECK (seq > 0),
    text TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_caption_session_seq UNIQUE (session_id, seq)
);
